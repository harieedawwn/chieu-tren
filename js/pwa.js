/* js/pwa.js  (owner SCREENS) fullscreen + install helpers and service worker registration. No dependencies; loads before screens.js.
 * API  TL.PWA
 *   fsSupported() / isFullscreen() / toggleFullscreen()   Fullscreen API with webkit fallback (false on iPhone Safari)
 *   standalone()        true when running as an installed app (display-mode fullscreen/standalone, or iOS navigator.standalone)
 *   ios()               iPhone / iPad / iPod
 *   canInstall() / install()   beforeinstallprompt captured; install() shows the browser prompt
 *   status()            {full: 'on'|'off'|'no'|'app', inst: 'can'|'ios'|'done'|'menu'}  what the settings rows show
 * The service worker (sw.js, generated by tools/build-pwa.js) is registered only over https. */
(function (TL) {
  'use strict';
  const d = document, de = d.documentElement, nav = navigator;
  let deferred = null;
  const mq = q => { try { return matchMedia(q).matches; } catch (e) { return false; } };
  const fsEl = () => d.fullscreenElement || d.webkitFullscreenElement || null;
  const fsReq = () => de.requestFullscreen || de.webkitRequestFullscreen || null;
  const fsExit = () => d.exitFullscreen || d.webkitExitFullscreen || null;
  const ios = () => /iPhone|iPad|iPod/i.test(nav.userAgent || '') || (nav.platform === 'MacIntel' && (nav.maxTouchPoints || 0) > 1);
  const standalone = () => mq('(display-mode: fullscreen)') || mq('(display-mode: standalone)') || nav.standalone === true;
  const fsSupported = () => !!fsReq() && d.fullscreenEnabled !== false;
  function toggleFullscreen() {
    try {
      if (fsEl()) { const x = fsExit(); if (x) x.call(d); }
      else { const q = fsReq(); if (q) { const p = q.call(de); if (p && p.catch) p.catch(() => {}); } }
    } catch (e) {}
  }
  function install() {
    if (!deferred) return Promise.resolve(false);
    const ev = deferred; deferred = null;
    try { ev.prompt(); return ev.userChoice.then(c => c && c.outcome === 'accepted', () => false); } catch (e) { return Promise.resolve(false); }
  }
  function status() {
    const full = standalone() ? 'app' : fsEl() ? 'on' : fsSupported() ? 'off' : 'no';
    const inst = standalone() ? 'done' : deferred ? 'can' : ios() ? 'ios' : 'menu';
    return { full: full, inst: inst };
  }
  window.addEventListener('beforeinstallprompt', e => { e.preventDefault(); deferred = e; });
  window.addEventListener('appinstalled', () => { deferred = null; });
  if ('serviceWorker' in nav && location.protocol === 'https:') {
    window.addEventListener('load', () => { nav.serviceWorker.register('sw.js').catch(() => {}); });
  }
  TL.PWA = { fsSupported: fsSupported, isFullscreen: () => !!fsEl(), toggleFullscreen: toggleFullscreen, standalone: standalone, ios: ios, canInstall: () => !!deferred, install: install, status: status };
})(globalThis.TL = globalThis.TL || {});
