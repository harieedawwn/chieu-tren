/* tools/build-pwa.js  node tools/build-pwa.js [--check] : writes sw.js (precache list + version hash of every game file) from index.html and assets.
 * Run before every commit that touches game files; --check (used by tests/pwa.check.js) fails when sw.js is stale. */
const fs = require('fs'), path = require('path'), crypto = require('crypto');
const root = path.join(__dirname, '..');
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const refs = [...html.matchAll(/(?:src|href)="([^"#]+)"/g)].map(m => m[1]).filter(u => !/^(https?:|data:)/.test(u));
const extra = ['./', 'manifest.webmanifest', 'assets/icon-192.png', 'assets/icon-512.png', 'assets/icon-maskable-512.png', 'assets/favicon-32.png', 'assets/favicon-64.png', 'assets/apple-touch-icon.png'];
const urls = [...new Set(['./', 'index.html'].concat(refs, extra))];
const h = crypto.createHash('sha1');
urls.forEach(u => { const f = path.join(root, u.split('?')[0] === './' ? 'index.html' : u.split('?')[0]); h.update(u); if (fs.existsSync(f)) h.update(fs.readFileSync(f)); });
const version = h.digest('hex').slice(0, 10);
const out = `/* sw.js — GENERATED by tools/build-pwa.js, do not edit. Precaches every game file; a new deploy changes VERSION, installs a fresh cache and drops the old. */
const VERSION = '${version}';
const CACHE = 'chieutren-' + VERSION;
const FILES = ${JSON.stringify(urls, null, 2)};
self.addEventListener('install', e => { e.waitUntil(caches.open(CACHE).then(c => Promise.all(FILES.map(u => c.add(new Request(u, { cache: 'reload' })).catch(() => null)))).then(() => self.skipWaiting())); });
self.addEventListener('activate', e => { e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => k.indexOf('chieutren-') === 0 && k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim())); });
self.addEventListener('fetch', e => {
  const q = e.request;
  if (q.method !== 'GET' || new URL(q.url).origin !== location.origin) return;
  if (q.mode === 'navigate') {   // network first so a new deploy shows at once; cache when offline
    e.respondWith(fetch(q).then(r => { const c = r.clone(); caches.open(CACHE).then(x => x.put('index.html', c)); return r; }).catch(() => caches.match('index.html').then(r => r || caches.match('./'))));
    return;
  }
  e.respondWith(caches.match(q).then(r => r || fetch(q).then(n => { if (n.ok) { const c = n.clone(); caches.open(CACHE).then(x => x.put(q, c)); } return n; })));
});
`;
const dest = path.join(root, 'sw.js');
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(dest) ? fs.readFileSync(dest, 'utf8') : '';
  if (cur !== out) { console.log('sw.js is stale: run node tools/build-pwa.js'); process.exit(1); }
  console.log('ok: sw.js up to date (' + version + ', ' + urls.length + ' files)');
} else { fs.writeFileSync(dest, out); console.log('sw.js written: ' + version + ', ' + urls.length + ' files'); }
